/** Raspakuje se pri prvoj pretrazi, ne pri pokretanju aplikacije. */
let cache: City[] | null = null;

function all(): City[] {
  if (cache) return cache;
  cache = PACKED.split('\n').map((line) => {
    const [id, name, ci, lat, lon, zi] = line.split('|');
    return {
      id: Number(id),
      name,
      country: COUNTRIES[Number(ci)],
      latitude: Number(lat),
      longitude: Number(lon),
      tz: ZONES[Number(zi)],
    };
  });
  return cache;
}

/** Skida dijakritike da pretraga radi i bez kvacica ("nis" -> "Nis"). */
function fold(s: string): string {
  return s
    .toLowerCase()
    .replace(/[čć]/g, 'c').replace(/š/g, 's').replace(/ž/g, 'z').replace(/đ/g, 'd')
    .normalize('NFD').replace(/[̀-ͯ]/g, '');
}

export function searchCities(query: string, limit = 8): City[] {
  const list = all();
  const q = fold(query.trim());
  if (!q) return list.slice(0, limit);

  const starts: City[] = [];
  const contains: City[] = [];
  for (const c of list) {
    const n = fold(c.name);
    if (n.startsWith(q)) starts.push(c);
    else if (n.includes(q)) contains.push(c);
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}

export function cityById(id: number): City | undefined {
  return all().find((c) => c.id === id);
}

