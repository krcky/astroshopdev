/** "2,3°" — decimalna zapirka, edna decimala. */
const stepenDecimalno = (x: number) => `${x.toFixed(1).replace('.', ',')}°`;

/** Redni broj: muski "1-ви, 2-ри, 7-ми, 14-ти", zenski "1-ва, 2-ра, 7-ма, 5-та". */
function redni(n: number, rod: 'm' | 'z'): string {
  const s = Math.abs(n) % 100;
  const d = Math.abs(n) % 10;
  const osnova = s >= 11 && s <= 19 ? 'т' : d === 1 ? 'в' : d === 2 ? 'р' : d === 7 || d === 8 ? 'м' : 'т';
  return `${n}-${osnova}${rod === 'm' ? 'и' : 'а'}`;
}

